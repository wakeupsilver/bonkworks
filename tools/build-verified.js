// Rebuilds verified.js: tests every compatible part pairing with pure physics (no Assist),
// placing the second part the way the game auto-places it, and records which ones work.
// Run from the bonkworks folder:  node tools/build-verified.js   (needs Playwright + Chromium)
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const dir = path.resolve(__dirname, '..');
  const b = await chromium.launch();
  const pg = await b.newPage();
  if (process.env.MATTER_LOCAL) await pg.route('**/matter.min.js', r => r.fulfill({ body: fs.readFileSync(process.env.MATTER_LOCAL), contentType: 'application/javascript' }));
  await pg.goto('file://' + path.join(dir, 'index.html'));
  await pg.waitForFunction(() => window.RG && RG.buildVerifiedTable, null, { timeout: 30000 });
  const table = await pg.evaluate(() => RG.buildVerifiedTable());
  const keys = Object.keys(table).sort();
  const ok = keys.filter(k => table[k]).length;
  const body = keys.map(k => `  "${k}": ${table[k]}`).join(',\n');
  fs.writeFileSync(path.join(dir, 'verified.js'),
    `// Generated by tools/build-verified.js: which part pairings work with pure physics when auto-placed.\n// ${ok} of ${keys.length} pairings pass.\nwindow.RG_VERIFIED = {\n${body}\n};\n`);
  console.log(`${ok} of ${keys.length} pairings pass`);
  console.log('failing:', keys.filter(k => !table[k]).join(' '));
  await b.close();
})();
